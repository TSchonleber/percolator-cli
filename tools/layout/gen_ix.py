"""From v16_program.rs generate (1) TS encoders, (2) a Rust example emitting test vectors."""
import re, sys, json
src = open(sys.argv[1]).read(); ops_all = json.load(open(sys.argv[2])); ts_out, rs_out = sys.argv[3], sys.argv[4]
ix = src[src.index("pub mod ix {"):]
def struct_body(text, kw, name):
    m = re.search(r"pub %s %s\s*\{" % (kw, name), text); i = m.end(); d = 1; j = i
    while d: d += {"{":1,"}":-1}.get(text[j],0); j += 1
    return re.sub(r"//[^\n]*", "", text[i:j-1])
def parse_fields(body):
    return re.findall(r"(?:pub\s+)?(\w+)\s*:\s*([^,\n]+?)\s*,", body)
enum = struct_body(ix, "enum", "Instruction")
variants = {}
for m in re.finditer(r"(\w+)\s*(\{[^{}]*\})?\s*,", enum):
    name, body = m.group(1), m.group(2)
    variants[name] = parse_fields(body[1:-1] + ",") if body else []
LEGS = {s: parse_fields(struct_body(ix, "struct", s) + ",") for s in ("BatchTradeLeg", "BatchTradeCpiLeg", "CrankObservationHint")}
VEC_ELEM = {"Vec<BatchTradeLeg>": "BatchTradeLeg", "Vec<BatchTradeCpiLeg>": "BatchTradeCpiLeg", "Vec<CrankObservationHint>": "CrankObservationHint"}
assert set(variants) == set(ops_all), (set(variants) ^ set(ops_all))

def camel(s): 
    p = s.split("_"); return p[0] + "".join(x.title() for x in p[1:])
TS_T = {"u8":"number","u16":"number","u32":"number","u64":"bigint | number","i64":"bigint | number",
        "u128":"bigint | number","i128":"bigint | number","[u8; 32]":"Bytes32","[[u8; 32]; 3]":"[Bytes32, Bytes32, Bytes32]"}
def ts_type(t): return f"{VEC_ELEM[t]}[]" if t in VEC_ELEM else TS_T[t]

# ---------------- TS ----------------
L = ['// GENERATED by layout/gen_ix.py from percolator-prog ix::Instruction::encode() — do not edit.',
     '// Wire format: tag byte, then little-endian fields in the exact order the program encodes them.',
     'import { PublicKey } from "@solana/web3.js";', '',
     'export type Bytes32 = PublicKey | Uint8Array;',
     'class W { private parts: Buffer[] = [];',
     '  u8(v: number) { const b = Buffer.alloc(1); b.writeUInt8(v); this.parts.push(b); }',
     '  u16(v: number) { const b = Buffer.alloc(2); b.writeUInt16LE(v); this.parts.push(b); }',
     '  u32(v: number) { const b = Buffer.alloc(4); b.writeUInt32LE(v); this.parts.push(b); }',
     '  u64(v: bigint | number) { const b = Buffer.alloc(8); b.writeBigUInt64LE(BigInt(v)); this.parts.push(b); }',
     '  i64(v: bigint | number) { const b = Buffer.alloc(8); b.writeBigInt64LE(BigInt(v)); this.parts.push(b); }',
     '  u128(v: bigint | number) { const x = BigInt(v); if (x < 0n || x >> 128n) throw new RangeError("u128 out of range"); this.u64(x & 0xffff_ffff_ffff_ffffn); this.u64(x >> 64n); }',
     '  i128(v: bigint | number) { const x = BigInt(v); if (x < -(1n << 127n) || x >= 1n << 127n) throw new RangeError("i128 out of range"); this.u128(BigInt.asUintN(128, x)); }',
     '  bytes32(v: Bytes32) { const b = Buffer.from(v instanceof PublicKey ? v.toBytes() : v); if (b.length !== 32) throw new RangeError("expected 32 bytes"); this.parts.push(b); }',
     '  done() { return Buffer.concat(this.parts); } }', '']
for s, fs in LEGS.items():
    L.append(f"export interface {s} {{ " + " ".join(f"{camel(f)}: {ts_type(t)};" for f, t in fs) + " }")
L.append("")
L.append("export const TAG = {")
for name, ops in ops_all.items(): L.append(f"  {name}: {ops[0][1]},")
L.append("} as const;\n")
for name, ops in ops_all.items():
    fields = variants[name]; tmap = dict(fields)
    if fields:
        L.append(f"export interface {name}Args {{ " + " ".join(f"{camel(f)}: {ts_type(t)};" for f, t in fields) + " }")
        L.append(f"export function enc{name}(a: {name}Args): Buffer {{")
    else:
        L.append(f"export function enc{name}(): Buffer {{")
    L.append("  const w = new W();")
    loopvar = None; loopelem = None
    for op in ops:
        k = op[0]
        if k == "tag": L.append(f"  w.u8({op[1]});")
        elif k == "len_u8":
            L.append(f"  if (a.{camel(op[1])}.length > 255) throw new RangeError('{op[1]}: too many'); w.u8(a.{camel(op[1])}.length);")
        elif k == "for":
            loopvar = op[1]; coll = op[2]
            L.append(f"  for (const {loopvar} of a.{camel(coll)}) {{")
        elif k == "endfor": L.append("  }"); loopvar = None
        else:
            ref = op[1]
            if loopvar and ref == loopvar: expr = loopvar
            elif loopvar and ref.startswith(loopvar + "."): expr = f"{loopvar}.{camel(ref.split('.',1)[1])}"
            else: expr = f"a.{camel(ref)}"
            meth = {"bytes": "bytes32"}.get(k, k)
            pre = "  " if loopvar else ""
            L.append(f"  {pre}w.{meth}({expr});")
    L.append("  return w.done();\n}\n")
open(ts_out, "w").write("\n".join(L))

# ---------------- Rust vectors ----------------
counter = [0]
def sentinel(t):
    counter[0] += 1; k = counter[0]
    if t == "u8": return f"{(k * 37) % 251 + 1}u8", str((k * 37) % 251 + 1)
    if t == "u16": v = (k * 7919) % 65000 + 300; return f"{v}u16", str(v)
    if t == "u32": v = (k * 2654435761) % 4_000_000_000 + 70000; return f"{v}u32", str(v)
    if t == "u64": v = (k * 0x9E3779B97F4A7C15) % (2**64); return f"{v}u64", str(v)
    if t == "i64": v = -((k * 0x9E3779B9) % (2**62)); return f"({v}i64)", str(v)
    if t == "u128": v = (k * 0x9E3779B97F4A7C15F39CC0605CEDC835) % (2**128); return f"{v}u128", str(v)
    if t == "i128": v = -((k * 0x9E3779B97F4A7C15F39CC0605CED) % (2**126)); return f"({v}i128)", str(v)
    if t == "[u8; 32]": return f"[{k % 256}u8; 32]", f"b32:{k % 256}"
    if t == "[[u8; 32]; 3]": return (f"[[{k%256}u8; 32], [{(k+1)%256}u8; 32], [{(k+2)%256}u8; 32]]", f"b32x3:{k%256}")
    raise ValueError(t)
R = ["// GENERATED by layout/gen_ix.py — emits instruction test vectors as JSON lines.",
     "use percolator_prog::ix::{Instruction as I, BatchTradeLeg, BatchTradeCpiLeg, CrankObservationHint};",
     "fn hex(b: &[u8]) -> String { b.iter().map(|x| format!(\"{:02x}\", x)).collect() }",
     "fn main() {"]
for name, fields in variants.items():
    if not fields:
        expr = f"I::{name}"; argsj = {}
    else:
        parts = []; argsj = {}
        for f, t in fields:
            if t in VEC_ELEM:
                elem = VEC_ELEM[t]; items = []; jitems = []
                for _ in range(2):
                    sub = []; js = {}
                    for lf, lt in LEGS[elem]:
                        r, j = sentinel(lt); sub.append(f"{lf}: {r}"); js[camel(lf)] = j
                    items.append(f"{elem} {{ {', '.join(sub)} }}"); jitems.append(js)
